/**
 * Phonetic transliterator for brand names and unmapped words
 */
function transliterate(word: string, lang: 'hi' | 'gu'): string {
  const lower = word.toLowerCase();

  const commonNames: Record<'hi' | 'gu', Record<string, string>> = {
    hi: {
      gir: 'गिर',
      amrit: 'अमृत',
      vedic: 'वैदिक',
      gjanand: 'गजानंद',
      surat: 'सूरत',
      banaskantha: 'बनासकांठा',
      ahmedabad: 'अहमदाबाद',
      junagadh: 'जूनागढ़',
      shree: 'श्री',
      kesar: 'केसर',
      chhas: 'छाछ',
    },
    gu: {
      gir: 'ગીર',
      amrit: 'અમૃત',
      vedic: 'વૈદિક',
      gjanand: 'ગજાનંદ',
      surat: 'સુરત',
      banaskantha: 'બનાસકાંઠા',
      ahmedabad: 'અમદાવાદ',
      junagadh: 'જૂનાગઢ',
      shree: 'શ્રી',
      kesar: 'કેસર',
      chhas: 'છાશ',
    },
  };

  if (commonNames[lang][lower]) {
    return commonNames[lang][lower];
  }

  const hiPhonetics: [RegExp, string][] = [
    [/sh/g, 'श'], [/chh/g, 'छ'], [/ch/g, 'च'], [/kh/g, 'ख'], [/gh/g, 'घ'],
    [/th/g, 'थ'], [/dh/g, 'ध'], [/ph/g, 'फ'], [/bh/g, 'भ'], [/jh/g, 'झ'],
    [/ee/g, 'ी'], [/oo/g, 'ू'], [/ai/g, 'ै'], [/au/g, 'ौ'],
    [/k/g, 'क'], [/g/g, 'ग'], [/c/g, 'क'], [/j/g, 'ज'], [/t/g, 'ट'],
    [/d/g, 'ड'], [/n/g, 'न'], [/p/g, 'प'], [/b/g, 'ब'], [/m/g, 'म'],
    [/y/g, 'य'], [/r/g, 'र'], [/l/g, 'ल'], [/v/g, 'व'], [/w/g, 'व'],
    [/s/g, 'स'], [/h/g, 'ह'], [/z/g, 'ज़'], [/x/g, 'क्स'],
    [/a/g, 'ा'], [/e/g, 'े'], [/i/g, 'ि'], [/o/g, 'ो'], [/u/g, 'ु'],
  ];

  const guPhonetics: [RegExp, string][] = [
    [/sh/g, 'શ'], [/chh/g, 'છ'], [/ch/g, 'ચ'], [/kh/g, 'ખ'], [/gh/g, 'ઘ'],
    [/th/g, 'થ'], [/dh/g, 'ધ'], [/ph/g, 'ફ'], [/bh/g, 'ભ'], [/jh/g, 'ઝ'],
    [/ee/g, 'ી'], [/oo/g, 'ૂ'], [/ai/g, 'ૈ'], [/au/g, 'ૌ'],
    [/k/g, 'ક'], [/g/g, 'ગ'], [/c/g, 'ક'], [/j/g, 'જ'], [/t/g, 'ટ'],
    [/d/g, 'ડ'], [/n/g, 'ન'], [/p/g, 'પ'], [/b/g, 'બ'], [/m/g, 'મ'],
    [/y/g, 'ય'], [/r/g, 'ર'], [/l/g, 'લ'], [/v/g, 'વ'], [/w/g, 'વ'],
    [/s/g, 'સ'], [/h/g, 'હ'], [/z/g, 'ઝ'], [/x/g, 'ક્સ'],
    [/a/g, 'ા'], [/e/g, 'ે'], [/i/g, 'િ'], [/o/g, 'ો'], [/u/g, 'ુ'],
  ];

  const rules = lang === 'hi' ? hiPhonetics : guPhonetics;
  let res = lower;
  for (const [pattern, replacement] of rules) {
    res = res.replace(pattern, replacement);
  }
  return res;
}

// ─── Translation hook ─────────────────────────────────────────
export function useTranslation() {
  const language = useStore((state) => state.language);
  const translationsCache = useStore((state) => state.translationsCache);

  // Get cached translations for current language, fall back to English cache, then static
  const currentLangMap: Record<string, string> = translationsCache[language] ?? {};
  const englishMap: Record<string, string> = translationsCache['en'] ?? {};
  
  // Get static fallback based on language
  const staticFallback = language === 'hi' ? HI_STATIC : language === 'gu' ? GU_STATIC : EN_STATIC;

  const t = (key: string, params?: Record<string, string>): string => {
    let str =
      currentLangMap[key] ??
      staticFallback[key] ??
      englishMap[key] ??
      EN_STATIC[key] ??
      key;

    if (params) {
      Object.entries(params).forEach(([paramKey, value]) => {
        str = str.replace(`{${paramKey}}`, value);
      });
    }

    return str;
  };

  /** Translate product title, description, tags, brand or attributes dynamically */
  const tProduct = (text: string | null | undefined): string => {
    if (!text) return '';
    if (language === 'hi' || language === 'gu') {
      const match = PRODUCT_TRANSLATIONS[language]?.[text];
      if (match) return match;

      // If text already has Indic characters, return as is
      if (/[\u0900-\u097F\u0A80-\u0AFF]/.test(text)) {
        return text;
      }

      // Dynamic token replacement for custom seller product names (e.g. "Test Product 2", "Test1")
      const tokens = text.split(/(\s+|[-_/(),])/);
      let anyTranslated = false;

      const translatedTokens = tokens.map((token) => {
        if (!token.trim() || /^[-_/(),]+$/.test(token)) {
          return token;
        }

        // Check if token has trailing digits like "Test1" -> "Test 1"
        const numMatch = token.match(/^([a-zA-Z]+)(\d+)$/);
        if (numMatch) {
          const w = numMatch[1].toLowerCase();
          const d = numMatch[2];
          const dictWord = WORD_DICTIONARY[language]?.[w];
          if (dictWord) {
            anyTranslated = true;
            return `${dictWord} ${d}`;
          }
          anyTranslated = true;
          return `${transliterate(numMatch[1], language)} ${d}`;
        }

        const lower = token.toLowerCase();
        const dictWord = WORD_DICTIONARY[language]?.[lower];
        if (dictWord) {
          anyTranslated = true;
          return dictWord;
        }

        // If it's a pure number or symbol, keep it
        if (/^\d+$/.test(token)) {
          return token;
        }

        // If it's alphabetical, transliterate
        if (/^[a-zA-Z]+$/.test(token)) {
          anyTranslated = true;
          return transliterate(token, language);
        }

        return token;
      });

      if (anyTranslated) {
        return translatedTokens.join('');
      }
    }
    return text;
  };

  /** Translate category or state names */
  const tCategory = (category: string | null | undefined): string => {
    if (!category) return '';
    if (language === 'hi' || language === 'gu') {
      const match = PRODUCT_TRANSLATIONS[language]?.[category];
      if (match) return match;
    }
    return category;
  };

  return { t, tProduct, tCategory, language };
}


