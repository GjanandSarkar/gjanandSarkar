/**
 * Recommendation scoring.
 *
 * Deliberately free of Supabase, React and `next/*` imports: these are pure
 * functions over plain arrays, so each strategy can be unit-tested and
 * reasoned about on its own. The data fetching lives in `engine.ts`.
 */

export type EventType = 'view' | 'add_to_cart' | 'purchase';

export interface ActivityEvent {
  user_id: string | null;
  session_id: string;
  product_id: string;
  event_type: EventType;
  created_at: string;
}

export interface ScoredProduct {
  productId: string;
  score: number;
  /** Which strategy produced this, for debugging and A/B analysis. */
  reason: 'popularity' | 'content' | 'collaborative';
}

/**
 * How much each event counts towards popularity.
 *
 * A purchase is a far stronger signal of worth than a view: it costs money and
 * cannot be generated by a bot trawling the catalogue. Weighting all three
 * equally would let high-traffic, low-converting products dominate every rail.
 */
export const EVENT_WEIGHTS: Record<EventType, number> = {
  view: 1,
  add_to_cart: 4,
  purchase: 10,
};

/** Popularity only looks this far back, so last month's hit does not rank forever. */
export const POPULARITY_WINDOW_DAYS = 30;

/** Recency half-life in days: a 15-day-old event counts half as much as today's. */
const HALF_LIFE_DAYS = 15;

/**
 * Exponential time decay. Returns 1.0 for an event happening now, 0.5 at one
 * half-life, and approaches 0 beyond that.
 */
export function recencyWeight(createdAt: string, now: number = Date.now()): number {
  const ageDays = (now - new Date(createdAt).getTime()) / 86_400_000;
  if (!Number.isFinite(ageDays) || ageDays < 0) return 1;
  return Math.pow(0.5, ageDays / HALF_LIFE_DAYS);
}

// ─── Strategy 1: popularity ─────────────────────────────────────────────────

/**
 * Rank products by recency-weighted engagement.
 *
 * This is the only strategy that works with no information about the visitor,
 * so it is also the fallback whenever a personalised strategy comes back thin.
 */
export function scoreByPopularity(
  events: ActivityEvent[],
  now: number = Date.now()
): ScoredProduct[] {
  const scores = new Map<string, number>();

  for (const ev of events) {
    const weight = EVENT_WEIGHTS[ev.event_type] ?? 0;
    const score = weight * recencyWeight(ev.created_at, now);
    scores.set(ev.product_id, (scores.get(ev.product_id) ?? 0) + score);
  }

  return toSorted(scores, 'popularity');
}

// ─── Strategy 2: content-based ──────────────────────────────────────────────

export interface ProductFeatures {
  id: string;
  category: string | null;
  brand?: string | null;
  tags?: string[] | null;
  price?: number | null;
}

/**
 * Similarity between two products, in 0..1.
 *
 * Category dominates because on a marketplace that partners with one company
 * per category, category is the strongest statement of what a product *is*.
 * Brand and tags refine within that, and a similar price point keeps a
 * recommender from answering a ₹200 browse with a ₹20,000 suggestion.
 */
export function similarity(a: ProductFeatures, b: ProductFeatures): number {
  if (a.id === b.id) return 0;

  let score = 0;

  if (a.category && b.category && a.category === b.category) score += 0.5;
  if (a.brand && b.brand && a.brand === b.brand) score += 0.2;

  const aTags = new Set((a.tags ?? []).map((t) => t.toLowerCase()));
  const bTags = (b.tags ?? []).map((t) => t.toLowerCase());
  if (aTags.size && bTags.length) {
    const shared = bTags.filter((t) => aTags.has(t)).length;
    // Jaccard-ish overlap, capped so tags can never outweigh category.
    score += 0.2 * (shared / Math.max(aTags.size, bTags.length));
  }

  if (a.price != null && b.price != null && a.price > 0 && b.price > 0) {
    const ratio = Math.min(a.price, b.price) / Math.max(a.price, b.price);
    // Only rewards genuinely comparable pricing: ratio 1.0 gives the full 0.1,
    // a 10x price gap gives almost nothing.
    score += 0.1 * ratio;
  }

  return Math.min(score, 1);
}

/**
 * Recommend products resembling a set of seed products (what the visitor just
 * viewed, or what is in their cart).
 */
export function scoreByContent(
  seeds: ProductFeatures[],
  catalogue: ProductFeatures[]
): ScoredProduct[] {
  if (seeds.length === 0) return [];

  const seedIds = new Set(seeds.map((s) => s.id));
  const scores = new Map<string, number>();

  for (const candidate of catalogue) {
    if (seedIds.has(candidate.id)) continue;

    // Best match against any seed, not the average. Averaging punishes a
    // product for being unlike the visitor's *other* interests, which is
    // wrong when someone is shopping across two unrelated categories.
    let best = 0;
    for (const seed of seeds) {
      const s = similarity(seed, candidate);
      if (s > best) best = s;
    }

    if (best > 0) scores.set(candidate.id, best);
  }

  return toSorted(scores, 'content');
}

// ─── Strategy 3: collaborative filtering ────────────────────────────────────

/**
 * Minimum number of distinct users who must share an interaction before a
 * co-occurrence is treated as a pattern rather than a coincidence.
 *
 * This is the guard against the classic thin-data failure: with two orders in
 * the database, every pair of products looks like a perfect match and the site
 * confidently claims "customers also bought" on a sample of one. Below this
 * threshold the strategy returns nothing and the hybrid falls back.
 */
export const MIN_CO_OCCURRENCE = 3;

/**
 * Item-to-item collaborative filtering.
 *
 * For the products the target user engaged with, find other users who engaged
 * with the same products, then score what *those* users also engaged with.
 * Item-to-item rather than user-to-user because the catalogue is far smaller
 * than the user base, so the co-occurrence matrix stays cheap to build.
 */
export function scoreByCollaborative(
  targetUserProductIds: string[],
  allEvents: ActivityEvent[],
  minCoOccurrence: number = MIN_CO_OCCURRENCE
): ScoredProduct[] {
  if (targetUserProductIds.length === 0) return [];

  const seed = new Set(targetUserProductIds);

  // Group every event by the actor behind it. A signed-out visitor is
  // identified by session, which is weaker but still a real person.
  const byActor = new Map<string, Set<string>>();
  for (const ev of allEvents) {
    const actor = ev.user_id ?? `session:${ev.session_id}`;
    let set = byActor.get(actor);
    if (!set) {
      set = new Set();
      byActor.set(actor, set);
    }
    set.add(ev.product_id);
  }

  // Count, per candidate product, how many distinct actors reached it from one
  // of the seed products. Counting distinct actors (not raw events) stops a
  // single obsessive user from manufacturing a recommendation on their own.
  const actorCounts = new Map<string, Set<string>>();

  for (const [actor, products] of byActor) {
    // Does this actor overlap with the target's interests at all?
    let overlaps = false;
    for (const p of products) {
      if (seed.has(p)) {
        overlaps = true;
        break;
      }
    }
    if (!overlaps) continue;

    for (const p of products) {
      if (seed.has(p)) continue;
      let actors = actorCounts.get(p);
      if (!actors) {
        actors = new Set();
        actorCounts.set(p, actors);
      }
      actors.add(actor);
    }
  }

  const scores = new Map<string, number>();
  for (const [productId, actors] of actorCounts) {
    if (actors.size < minCoOccurrence) continue;
    scores.set(productId, actors.size);
  }

  return toSorted(scores, 'collaborative');
}

// ─── Strategy 4: hybrid ─────────────────────────────────────────────────────

/**
 * Relative trust in each strategy when blending.
 *
 * Collaborative evidence outranks content similarity because "real people who
 * liked this also liked that" beats "these share a category". Popularity is
 * weighted lowest: it is the least personal signal and would otherwise flatten
 * every rail into the same bestseller list.
 */
export const STRATEGY_WEIGHTS = {
  collaborative: 1.0,
  content: 0.6,
  popularity: 0.35,
} as const;

/**
 * Merge strategy outputs into one ranking.
 *
 * Each strategy's scores are normalised to 0..1 first. Without that, raw
 * magnitudes are incomparable — popularity scores run into the hundreds while
 * content similarity never exceeds 1, so the blend would be pure popularity.
 */
export function hybridScore(lists: ScoredProduct[][]): ScoredProduct[] {
  const combined = new Map<string, { score: number; reason: ScoredProduct['reason'] }>();

  for (const list of lists) {
    if (list.length === 0) continue;

    const max = Math.max(...list.map((r) => r.score));
    if (max <= 0) continue;

    for (const item of list) {
      const weight = STRATEGY_WEIGHTS[item.reason] ?? 0.5;
      const contribution = (item.score / max) * weight;
      const existing = combined.get(item.productId);

      if (!existing) {
        combined.set(item.productId, { score: contribution, reason: item.reason });
      } else {
        existing.score += contribution;
        // Attribute the result to whichever strategy argued hardest for it.
        if (contribution > (STRATEGY_WEIGHTS[existing.reason] ?? 0.5) / 2) {
          existing.reason = item.reason;
        }
      }
    }
  }

  return Array.from(combined.entries())
    .map(([productId, v]) => ({ productId, score: v.score, reason: v.reason }))
    .sort((a, b) => b.score - a.score || a.productId.localeCompare(b.productId));
}

// ─── Diversity and repetition safeguards ────────────────────────────────────

/**
 * Stop a rail becoming eight variations of one thing.
 *
 * A pure relevance sort on a marketplace reliably returns the same category
 * over and over, which looks broken and teaches customers to ignore the rail.
 * This keeps the ranking but caps how many entries any one category may claim,
 * backfilling from the remainder if the cap leaves the rail short.
 */
export function diversify<T extends { productId: string }>(
  ranked: T[],
  categoryOf: (productId: string) => string | null,
  limit: number,
  maxPerCategory = 2
): T[] {
  const picked: T[] = [];
  const counts = new Map<string, number>();
  const overflow: T[] = [];

  for (const item of ranked) {
    if (picked.length >= limit) break;
    const cat = categoryOf(item.productId) ?? '__none__';
    const used = counts.get(cat) ?? 0;

    if (used >= maxPerCategory) {
      overflow.push(item);
      continue;
    }
    counts.set(cat, used + 1);
    picked.push(item);
  }

  // Better to show a slightly repetitive rail than a half-empty one.
  for (const item of overflow) {
    if (picked.length >= limit) break;
    picked.push(item);
  }

  return picked;
}

/**
 * Remove products the customer has no reason to see again: what is already in
 * their cart, and what they recently bought. Recommending a just-purchased
 * item is the most visible way a recommender signals that it is not paying
 * attention.
 */
export function excludeIds<T extends { productId: string }>(
  ranked: T[],
  exclude: Iterable<string>
): T[] {
  const blocked = new Set(exclude);
  return ranked.filter((r) => !blocked.has(r.productId));
}

// ─── internals ──────────────────────────────────────────────────────────────

function toSorted(
  scores: Map<string, number>,
  reason: ScoredProduct['reason']
): ScoredProduct[] {
  return Array.from(scores.entries())
    .map(([productId, score]) => ({ productId, score, reason }))
    // Tie-break on id so the ordering is stable across requests; an unstable
    // rail that reshuffles on refresh reads as a bug.
    .sort((a, b) => b.score - a.score || a.productId.localeCompare(b.productId));
}
